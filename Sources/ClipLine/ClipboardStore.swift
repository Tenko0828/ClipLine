import AppKit
import CryptoKit
import ImageIO

enum ClipKind: String, Codable {
    case text, image, files, scene
}

struct ClipItem: Identifiable, Codable, Equatable {
    let id: UUID
    var kind: ClipKind
    var text: String?
    var imageFile: String?
    var imageHash: String?
    var imageSize: CGSize?
    var filePaths: [String]?
    var scene: SceneData?
    var date: Date
    var pinned: Bool
    /// 每张卡片固定的随机倾斜角，让绳子上的东西看起来自然一点
    var tilt: Double
}

/// 轮询系统剪贴板，维护历史记录并持久化到 ~/Library/Application Support/ClipLine
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    private let maxUnpinned = 60
    private var lastChange = -1
    private var timer: Timer?
    private var thumbs: [UUID: NSImage] = [:]

    let dir: URL
    private var imagesDir: URL { dir.appendingPathComponent("images", isDirectory: true) }
    private var indexURL: URL { dir.appendingPathComponent("history.json") }

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipLine", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        load()
    }

    /// 固定的在最左边，其余按时间从新到旧
    var displayItems: [ClipItem] {
        items.sorted { a, b in
            if a.pinned != b.pinned { return a.pinned }
            return a.date > b.date
        }
    }

    func start() {
        poll()
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: - 读取剪贴板

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard let types = pb.types, !types.isEmpty else { return }
        if types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) { return }

        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            addFiles(urls)
            return
        }

        // 图片和文字同时存在时，以来源 app 声明的优先类型为准
        let imageTypes: [(NSPasteboard.PasteboardType, String)] = [
            (.png, "png"), (.tiff, "tiff"), (NSPasteboard.PasteboardType("public.jpeg"), "jpg"),
        ]
        let imageIndex = types.firstIndex { t in imageTypes.contains { $0.0 == t } }
        let stringIndex = types.firstIndex(of: .string)
        if let ii = imageIndex, stringIndex == nil || ii < stringIndex! {
            let type = types[ii]
            let ext = imageTypes.first { $0.0 == type }!.1
            if let data = pb.data(forType: type) {
                addImage(data, ext: ext)
                return
            }
        }

        if let s = pb.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            addText(s)
        }
    }

    private func newItem(_ kind: ClipKind) -> ClipItem {
        ClipItem(id: UUID(), kind: kind, date: Date(), pinned: false,
                 tilt: Double.random(in: -4.5...4.5))
    }

    private func addText(_ s: String) {
        if let i = items.firstIndex(where: { $0.kind == .text && $0.text == s }) {
            items[i].date = Date()
        } else {
            var item = newItem(.text)
            item.text = s
            items.append(item)
        }
        trimAndSave()
    }

    private func addImage(_ data: Data, ext: String) {
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        if let i = items.firstIndex(where: { $0.kind == .image && $0.imageHash == hash }) {
            items[i].date = Date()
            trimAndSave()
            return
        }
        var item = newItem(.image)
        let file = "\(item.id.uuidString).\(ext)"
        do {
            try data.write(to: imagesDir.appendingPathComponent(file))
        } catch {
            return
        }
        item.imageFile = file
        item.imageHash = hash
        if let src = CGImageSourceCreateWithData(data as CFData, nil),
           let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
           let w = props[kCGImagePropertyPixelWidth] as? Int,
           let h = props[kCGImagePropertyPixelHeight] as? Int {
            item.imageSize = CGSize(width: w, height: h)
        }
        items.append(item)
        trimAndSave()
    }

    private func addFiles(_ urls: [URL]) {
        let paths = urls.map(\.path)
        if let i = items.firstIndex(where: { $0.kind == .files && $0.filePaths == paths }) {
            items[i].date = Date()
        } else {
            var item = newItem(.files)
            item.filePaths = paths
            items.append(item)
        }
        trimAndSave()
    }

    // MARK: - 场景

    func addScene(_ scene: SceneData) {
        var item = newItem(.scene)
        item.scene = scene
        item.pinned = true
        items.append(item)
        save()
    }

    // MARK: - 转换

    /// 把加工后的文字挂上绳子并写进剪贴板
    func addTransformed(_ text: String) {
        addText(text)
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
    }

    func applyTransform(_ t: Transform, to item: ClipItem, completion: @escaping (Bool) -> Void) {
        switch item.kind {
        case .text:
            guard let r = t.textResult(item.text ?? "") else { return completion(false) }
            addTransformed(r)
            completion(true)
        case .scene:
            completion(false)
        case .files:
            guard let r = t.fileResult(item.filePaths ?? []) else { return completion(false) }
            addTransformed(r)
            completion(true)
        case .image:
            guard let url = imageURL(item) else { return completion(false) }
            Transform.recognizeText(at: url) { [weak self] r in
                guard let self, let r else { return completion(false) }
                self.addTransformed(r)
                completion(true)
            }
        }
    }

    // MARK: - 写回剪贴板

    func copyToPasteboard(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(item), let data = try? Data(contentsOf: url) {
                let type: NSPasteboard.PasteboardType = switch url.pathExtension {
                case "png": .png
                case "jpg": NSPasteboard.PasteboardType("public.jpeg")
                default: .tiff
                }
                pb.setData(data, forType: type)
                // 部分 app 只认 TIFF，顺手补一份
                if type != .tiff, let rep = NSBitmapImageRep(data: data), let tiff = rep.tiffRepresentation {
                    pb.setData(tiff, forType: .tiff)
                }
            }
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        case .scene:
            break
        }
        lastChange = pb.changeCount
    }

    func bump(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].date = Date()
        save()
    }

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        trimAndSave()
    }

    func delete(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        removeFiles(of: items[i])
        items.remove(at: i)
        save()
    }

    func clearUnpinned() {
        for item in items where !item.pinned { removeFiles(of: item) }
        items.removeAll { !$0.pinned }
        save()
    }

    // MARK: - 图片与拖拽

    func imageURL(_ item: ClipItem) -> URL? {
        item.imageFile.map { imagesDir.appendingPathComponent($0) }
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        if let t = thumbs[item.id] { return t }
        guard let url = imageURL(item), let src = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 420,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let img = NSImage(cgImage: cg, size: .zero)
        thumbs[item.id] = img
        return img
    }

    func itemProvider(for item: ClipItem) -> NSItemProvider {
        switch item.kind {
        case .text:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .image:
            return imageURL(item).flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        case .scene:
            return NSItemProvider()
        case .files:
            return item.filePaths?.first.flatMap { NSItemProvider(contentsOf: URL(fileURLWithPath: $0)) } ?? NSItemProvider()
        }
    }

    // MARK: - 持久化

    private func removeFiles(of item: ClipItem) {
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
        thumbs[item.id] = nil
    }

    private func trimAndSave() {
        let unpinned = items.filter { !$0.pinned }.sorted { $0.date > $1.date }
        if unpinned.count > maxUnpinned {
            let drop = Set(unpinned[maxUnpinned...].map(\.id))
            for item in items where drop.contains(item.id) { removeFiles(of: item) }
            items.removeAll { drop.contains($0.id) }
        }
        save()
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: indexURL, options: .atomic)
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved.filter { item in
            guard item.kind == .image else { return true }
            return imageURL(item).map { FileManager.default.fileExists(atPath: $0.path) } ?? false
        }
    }
}
